export type ContentIconName = keyof typeof contentIconMap;

export const isContentIconName = (name: string): name is ContentIconName =>
  Object.prototype.hasOwnProperty.call(contentIconMap, name);

/** Content stores icon names as plain strings; unknown names render as `Info`. */
export const getContentIcon = (name: string): LucideIcon =>
  isContentIconName(name) ? contentIconMap[name] : Info;

