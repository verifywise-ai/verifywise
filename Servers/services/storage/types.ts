/**
 * Shared contracts for the file-storage abstraction.
 *
 * A "storage key" is the provider-specific identifier of a stored object
 * (e.g. an S3 object key). Rows in the `files` table record where their bytes
 * live via the nullable `storage_provider` / `storage_key` columns:
 * when both are NULL the bytes are in the row's `content` column (the
 * historical default, handled by the local/database provider).
 */

export type StorageProvider = "local" | "s3";

/**
 * Where a file's bytes were stored. `key` is null for the local provider,
 * whose bytes live in the `files.content` column rather than an object store.
 */
export interface StorageObjectRef {
  provider: StorageProvider;
  key: string | null;
}

export interface PutObjectInput {
  /** Storage key generated by the caller (see buildStorageKey). */
  key: string;
  body: Buffer;
  contentType: string;
}

export interface SignedUrlOptions {
  /** Lifetime of the signed URL in seconds. Provider defaults apply when unset. */
  expiresInSeconds?: number;
}

/**
 * Base error for all storage failures. Messages must never include
 * credentials, endpoint URLs with embedded userinfo, or secret config values.
 */
export class StorageError extends Error {
  constructor(
    message: string,
    public readonly provider?: StorageProvider,
    public readonly cause?: unknown,
  ) {
    super(message);
    this.name = "StorageError";
  }
}

/** Invalid or incomplete storage configuration (e.g. missing env vars). */
export class StorageConfigError extends StorageError {
  constructor(message: string) {
    super(message);
    this.name = "StorageConfigError";
  }
}

/** The requested object does not exist in the backing store. */
export class StorageNotFoundError extends StorageError {
  constructor(
    message: string,
    public readonly key?: string,
  ) {
    super(message);
    this.name = "StorageNotFoundError";
  }
}

/** The operation is not meaningful for this provider (e.g. signUrl on local). */
export class StorageUnsupportedError extends StorageError {
  constructor(message: string) {
    super(message);
    this.name = "StorageUnsupportedError";
  }
}
